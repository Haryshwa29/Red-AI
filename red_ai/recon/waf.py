"""Web Application Firewall detection (read-only).

Completes the firewall picture on the web side: a network firewall filters
ports; a WAF filters HTTP requests. This sends one benign request and one
obviously-malicious-LOOKING request (an XSS/SQLi/traversal string in throwaway
params — never a real exploit) and decides a WAF is present when either:

  * the malicious request is blocked (403/406/501/429/…) while the benign one
    is not — behavioral evidence, or
  * a known WAF vendor signature appears in the response headers/body.

Knowing a WAF is in front changes how you read every later result (a "closed"
app may just be filtered), which is exactly what the operator needs to see.
"""
from __future__ import annotations

import re
import ssl
import urllib.request
from typing import Callable, Optional

Opener = Callable[[str, float], tuple]   # (url, timeout) -> (status, headers: dict, body: str)

# Obviously-malicious-looking but inert: throwaway params, no real target reached.
_ATTACK_QS = ("?q=<script>alert(1)</script>"
              "&id=1%27%20OR%20%271%27%3D%271%27%20UNION%20SELECT%20NULL--%20-"
              "&f=../../../../etc/passwd")

_BLOCK_STATUS = {403, 406, 501, 419, 429, 999}

# (signature regex over headers+body, vendor). Case-insensitive.
_SIGNATURES = [
    (r"cf-ray|server:\s*cloudflare|attention required! \| cloudflare", "Cloudflare"),
    (r"server:\s*akamaighost|x-akamai|akamai", "Akamai"),
    (r"x-sucuri-id|x-sucuri-cache|sucuri website firewall", "Sucuri"),
    (r"x-iinfo|incap_ses|visid_incap|incapsula", "Imperva Incapsula"),
    (r"mod_security|modsecurity|this error was generated by mod_security|naxsi", "ModSecurity"),
    (r"the requested url was rejected|x-waf-event|\bbig-?ip\b", "F5 BIG-IP ASM"),
    (r"barra_counter_session|barracuda", "Barracuda"),
    (r"fortiwafsid|fortiweb|fortigate", "Fortinet FortiWeb"),
    (r"generated by wordfence", "Wordfence"),
    (r"x-amzn-waf|aws.{0,10}waf|request blocked.*request id", "AWS WAF"),
    (r"x-distil|distil", "Imperva Distil"),
]


def _default_opener(url: str, timeout: float) -> tuple:
    ctx = ssl._create_unverified_context() if url.lower().startswith("https") else None
    req = urllib.request.Request(url, headers={"User-Agent": "RED-AI-recon/1.0"})
    try:
        with urllib.request.urlopen(req, timeout=timeout, context=ctx) as r:
            body = r.read(8192).decode("utf-8", "replace")
            return r.status, {k.lower(): v for k, v in r.headers.items()}, body
    except urllib.error.HTTPError as e:   # a block is usually an HTTP error status
        try:
            body = e.read(8192).decode("utf-8", "replace")
        except Exception:
            body = ""
        return e.code, {k.lower(): v for k, v in (e.headers or {}).items()}, body
    except Exception:
        return 0, {}, ""


def _blob(status: int, headers: dict, body: str) -> str:
    hdr = "\n".join(f"{k}: {v}" for k, v in (headers or {}).items())
    return f"{hdr}\n{body}".lower()


def detect_waf(base_url: str, opener: Optional[Opener] = None) -> dict:
    """Return {type, present, vendor, evidence, blocked_status}. Never raises."""
    opener = opener or _default_opener
    base = base_url.rstrip("/")
    try:
        bs, bh, bb = opener(base + "/", 6.0)
        as_, ah, ab = opener(base + "/" + _ATTACK_QS, 6.0)
    except Exception:
        return {"type": "waf", "present": False, "vendor": None, "evidence": "probe failed", "blocked_status": None}

    blob = _blob(bs, bh, bb) + "\n" + _blob(as_, ah, ab)
    vendor = next((v for rx, v in _SIGNATURES if re.search(rx, blob, re.I)), None)

    behavioral = bs not in _BLOCK_STATUS and as_ in _BLOCK_STATUS
    present = bool(vendor) or behavioral
    if behavioral and not vendor:
        ev = f"malicious-looking request returned HTTP {as_} while the benign request returned HTTP {bs}"
    elif vendor:
        ev = f"response carries a {vendor} signature" + (f"; malicious request blocked (HTTP {as_})" if behavioral else "")
    else:
        ev = "no WAF signature or blocking observed"
    return {"type": "waf", "present": present, "vendor": vendor, "evidence": ev,
            "blocked_status": as_ if behavioral else None}
